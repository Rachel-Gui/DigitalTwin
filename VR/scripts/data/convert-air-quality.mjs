import fs from "node:fs/promises";
import path from "node:path";
import XLSX from "xlsx";

const workspaceRoot = path.resolve(import.meta.dirname, "../../..");
const sourcePath = path.join(workspaceRoot, "03_数据/PM25与风场/pm25_with_wind.xlsx");
const outputPath = path.join(import.meta.dirname, "../../app/data/airQualityData.ts");
const sourceSha256 = "80ea76c9f2ba4770d10339bbadd6f5302c23e4c987f3ada928cecd8cbe75f756";

function pad(value) {
  return String(value).padStart(2, "0");
}

function finiteOrNull(value) {
  if (value === null || value === undefined || value === "") return null;
  const number = Number(value);
  return Number.isFinite(number) ? number : null;
}

function round(value, digits = 6) {
  return value === null ? null : Number(value.toFixed(digits));
}

function dateKey(serial) {
  const parsed = XLSX.SSF.parse_date_code(serial);
  if (!parsed) throw new Error(`Invalid Excel time value: ${serial}`);
  return Number(`${parsed.y}${pad(parsed.m)}${pad(parsed.d)}${pad(parsed.H)}`);
}

const workbook = XLSX.readFile(sourcePath, { cellDates: false });
const worksheet = workbook.Sheets[workbook.SheetNames[0]];
const sourceRows = XLSX.utils.sheet_to_json(worksheet, { defval: null, raw: true });
const tuples = sourceRows.map((row) => [
  dateKey(row.time),
  round(finiteOrNull(row["pm25(碌g/m鲁)"] ?? row["pm25(µg/m³)"] ?? row.pm25), 3),
  round(finiteOrNull(row.HourlyWindDirection), 3),
  round(finiteOrNull(row.HourlyWindSpeed), 3),
  round(finiteOrNull(row.street_speed), 6) ?? 0,
  round(finiteOrNull(row.wind_u), 6) ?? 0,
  round(finiteOrNull(row.wind_v), 6) ?? 0,
]);

const days = [];
for (let start = 0; start < tuples.length;) {
  const dayKey = Math.trunc(tuples[start][0] / 100);
  let end = start + 1;
  while (end < tuples.length && Math.trunc(tuples[end][0] / 100) === dayKey) end += 1;
  const text = String(dayKey);
  days.push({ date: `${text.slice(0, 4)}-${text.slice(4, 6)}-${text.slice(6, 8)}`, start, count: end - start });
  start = end;
}

const source = `// Generated by scripts/data/convert-air-quality.mjs from the original Grasshopper Excel source.\n` +
`// Runtime code has no Excel or JSON fetch dependency. Do not edit rows manually.\n\n` +
`export type EmbeddedAirQualityRow = readonly [\n` +
`  localDateHour: number, pm25UgM3: number, windDirectionDeg: number | null,\n` +
`  windSpeedMS: number | null, streetSpeedMS: number, windU: number, windV: number,\n` +
`];\n\n` +
`export const AIR_QUALITY_SOURCE = {\n` +
`  file: "pm25_with_wind.xlsx",\n` +
`  sha256: "${sourceSha256}",\n` +
`  sheet: "${workbook.SheetNames[0]}",\n` +
`  timezone: "America/Los_Angeles",\n` +
`  latitude: 47.528225,\n` +
`  longitude: -122.322992,\n` +
`  recordCount: ${tuples.length},\n` +
`  firstLocalHour: "${days[0].date} ${String(tuples[0][0]).slice(-2)}:00",\n` +
`  lastLocalHour: "${days.at(-1).date} ${String(tuples.at(-1)[0]).slice(-2)}:00",\n` +
`} as const;\n\n` +
`export const AIR_QUALITY_DAYS = ${JSON.stringify(days)} as const;\n\n` +
`export const AIR_QUALITY_ROWS: readonly EmbeddedAirQualityRow[] = [\n` +
tuples.map((row) => `  ${JSON.stringify(row)},`).join("\n") +
`\n];\n`;

await fs.writeFile(outputPath, source);
console.log(JSON.stringify({ source: sourcePath, output: outputPath, records: tuples.length, days: days.length }, null, 2));
